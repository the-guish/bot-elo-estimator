#!/usr/bin/env python3
"""Turn the registry into Docker builds: the order build_docker.sh builds in, each image's build
context, and the engines a change affects, for CI."""

import argparse
import json
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from botelo.registry import IMAGE_PREFIX, REGISTRY, ROOT, Registry, load  # noqa: E402

SMOKE_TEST = ROOT / "images" / "common" / "smoke_test.sh"
UBUNTU = "ubuntu:26.04"
# A change to one of these can break any engine's build or any image.
SHARED = ("images/common/", "build_docker.sh", "lib/botelo/images.py", "lib/botelo/registry.py",
          ".github/workflows/images.yml")


def engine_tag(engine: str) -> str:
    return f"{IMAGE_PREFIX}engine-{engine}"


def test_tag(engine: str) -> str:
    return f"{IMAGE_PREFIX}test-{engine}"


# --- Pure functions --------------------------------------------------------


def plan(registry: Registry, target: str) -> list[tuple[str, str]]:
    """The builds `target` needs, in order: ("engine", name) and ("image", name) steps. The target
    is an image, or `test-<engine>` for one engine alone."""
    if target.startswith("test-"):
        engine = target.removeprefix("test-")
        if engine not in registry.engines:
            raise KeyError(f"no engine {engine}")
        return [("engine", engine), ("test", engine)]
    if target not in registry.images:
        raise KeyError(f"no image {target}")
    chain = registry.chain(target)
    return [("engine", e) for image in chain for e in image.engines] + [("image", i.name) for i in chain]


def dockerfile(registry: Registry, engines: list[str], parent: str | None, tag: str) -> str:
    """An image's Dockerfile: its engines' files, their runtime packages, and a wrapper on PATH per
    command. The smoke test runs last, so the build fails unless every command answers."""
    lines = [
        f"# {tag}, generated by lib/botelo/images.py from bots.toml. Build it with build_docker.sh.",
        "",
    ]
    if parent is None:
        lines.append(f"ARG BASE={UBUNTU}")
    else:
        lines.append(f"ARG PARENT={IMAGE_PREFIX}{parent}")
    lines += [f"FROM {engine_tag(e)} AS {e}" for e in engines]
    lines += ["", "FROM ${BASE}" if parent is None else "FROM ${PARENT}", ""]
    runtime = sorted({p for e in engines for p in registry.engines[e].runtime})
    if runtime:
        lines += [
            "ENV DEBIAN_FRONTEND=noninteractive",
            "RUN apt-get update \\",
            f"    && apt-get install -y --no-install-recommends {' '.join(runtime)} \\",
            "    && rm -rf /var/lib/apt/lists/*",
            "",
        ]
    lines += [f"COPY --from={e} /opt/engines/ /opt/engines/" for e in engines]
    lines += ["COPY bin/ /opt/engines/bin/", "COPY smoke/ /opt/engines/smoke/", ""]
    if parent is None:
        lines += ["ENV PATH=/opt/engines/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin", ""]
    lines += ["# Every command of the image answers one search, or the build fails.", "RUN smoke_test", "",
              'CMD ["bash"]']
    return "\n".join(lines) + "\n"


def smoke_lines(registry: Registry, engines: list[str]) -> str:
    """The smoke test's list: command, go and expect, separated by tabs."""
    rows = []
    for engine in engines:
        for command in registry.engines[engine].commands.values():
            if command.smoke:
                rows.append("\t".join(filter(None, (command.name, command.go, command.expect))))
    return "".join(row + "\n" for row in rows)


def write_context(registry: Registry, step: str, name: str, out: Path) -> str:
    """Writes the build context of an image, or of an engine's test image, into `out`, and returns
    the image's tag."""
    if step == "test":
        engines, parent, tag = [name], None, test_tag(name)
    else:
        image = registry.images[name]
        engines, parent, tag = image.engines, image.parent, image.tag
    (out / "bin").mkdir(parents=True, exist_ok=True)
    (out / "smoke").mkdir(exist_ok=True)
    (out / "Dockerfile").write_text(dockerfile(registry, engines, parent, tag), encoding="utf-8")
    (out / "smoke" / f"{name}.tsv").write_text(smoke_lines(registry, engines), encoding="utf-8")
    for engine in engines:
        for command in registry.engines[engine].commands.values():
            wrapper = out / "bin" / command.name
            wrapper.write_text(command.wrapper(), encoding="utf-8")
            wrapper.chmod(0o755)
    if parent is None:
        shutil.copy(SMOKE_TEST, out / "bin" / "smoke_test")
        (out / "bin" / "smoke_test").chmod(0o755)
    return tag


def affected(old: dict | None, new: dict, changed: list[str], full: bool = False) -> dict:
    """The engines to build, and whether to build the images, after a change: `old` and `new` are
    bots.toml's tables before and after, None when it did not exist, and `changed` the paths.

    An engine's own build ends with a test image of its commands, made like the images are, so a
    new or changed engine needs no image build. The images build when what they all share changes,
    or their parents do. With `full`, they also build when an engine or an image's engines change."""
    # Pending engines are not built until someone takes them up.
    engines = sorted(e for e, table in new.get("engines", {}).items() if not table.get("pending"))
    if old is None or any(path.startswith(SHARED) for path in changed):
        return {"engines": engines, "images": True}
    touched = sorted(
        e for e in engines
        if any(path.startswith(f"images/engines/{e}/") for path in changed)
        or old.get("engines", {}).get(e) != new["engines"][e]
    )
    old_images, new_images = old.get("images", {}), new.get("images", {})
    parents = {name: table.get("parent") for name, table in old_images.items()}
    structure = parents != {name: table.get("parent") for name, table in new_images.items()}
    images = structure or (full and (bool(touched) or old_images != new_images))
    return {"engines": touched, "images": images}


# --- Commands --------------------------------------------------------------


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def affected_since(base: str | None, full: bool) -> dict:
    new = tomllib.loads(REGISTRY.read_text(encoding="utf-8"))
    # A new branch's push has no commit before it: GitHub sends zeros.
    if base is None or set(base) == {"0"}:
        return affected(None, new, [])
    changed = git("diff", "--name-only", base, "HEAD").split()
    try:
        old = tomllib.loads(git("show", f"{base}:bots.toml"))
    except subprocess.CalledProcessError:
        old = None
    return affected(old, new, changed, full)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    steps = sub.add_parser("plan", help="the builds a target needs, one per line")
    steps.add_argument("target", help="an image, or test-<engine>")
    context = sub.add_parser("context", help="write an image's build context and print its tag")
    context.add_argument("step", choices=("image", "test"))
    context.add_argument("name")
    context.add_argument("out", type=Path)
    since = sub.add_parser("affected", help="the engines a change since a commit affects, as JSON")
    since.add_argument("--base", help="the commit before the change; all engines without one")
    since.add_argument("--full", action="store_true", help="build the images after any engine change")
    sub.add_parser("default", help="the image build_docker.sh builds by default: the last one")
    args = parser.parse_args()

    if args.action == "affected":
        print(json.dumps(affected_since(args.base, args.full)))
        return 0
    registry = load()
    if args.action == "plan":
        try:
            steps = plan(registry, args.target)
        except KeyError as error:
            print(error.args[0], file=sys.stderr)
            return 2
        for step, name in steps:
            print(step, name)
    elif args.action == "context":
        print(write_context(registry, args.step, args.name, args.out))
    else:
        print(list(registry.images)[-1])
    return 0


if __name__ == "__main__":
    sys.exit(main())
